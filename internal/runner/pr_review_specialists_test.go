// tokensCosting is one step the harness reports as costing cost dollars.
func tokensCosting(cost string) string {
	return `{"type":"step_finish","part":{"tokens":{"input":1000,"output":100},"cost":` + cost + `}}` + "\n"
}

// areaOf is the configured area name with its models replaced.
func areaOf(t *testing.T, name string, models ...string) ReviewArea {
	t.Helper()
	for _, a := range ReviewAreas() {
		if a.Name == name {
			a.Models = models
			return a
		}
	}
	t.Fatalf("no review area %q", name)
	return ReviewArea{}
}

// contextTouching is a review context whose diff touches the data and infra areas.
func contextTouching() PRReviewContext {
	c := validPRContext()
	c.Diff = plain("internal/store/x.go") + plain("infra/main.tf")
	return c
}

func passOf(areas ...ReviewArea) SpecialistPass {
	return SpecialistPass{Areas: areas, Deadline: time.Now().Add(time.Hour)}
}

func specialistNames(v PRVerdict) []string {
	var names []string
	for _, s := range v.Specialists {
		names = append(names, s.Name)
	}
	return names
}

func outcomesOf(attempts []PRReviewAttempt) []string {
	var out []string
	for _, a := range attempts {
		out = append(out, a.Outcome)
	}
	return out
}

// TestReviewPRWithSpecialistsMakesTheGeneralCallsAloneForADiffTouchingNoArea: with
// no area touched the agent sees the general prompt alone and the verdict JSON is
// what ReviewPR wrote before specialists existed. The goldens were generated by
// the code on origin/main, not by this change.
func TestReviewPRWithSpecialistsMakesTheGeneralCallsAloneForADiffTouchingNoArea(t *testing.T) {
	failing := func(context.Context, io.Writer) error { return errors.New("exit status 1") }
	const (
		usage    = `"usage":{"input":1000,"output":100,"reasoning":0,"cache_read":0,"cache_write":0,"cost":0,"steps":1}`
		noUsage  = `"usage":{"input":0,"output":0,"reasoning":0,"cache_read":0,"cache_write":0,"cost":0,"steps":0}`
		reviewed = `"attempts":[{"model":"gemini/gemini-3.8-flash","outcome":"reviewed","cost":0}]`
	)
	for name, tt := range map[string]struct {
		reply  func(context.Context, io.Writer) error
		stderr map[string]string
		golden string
	}{
		"clean": {replyWith(usedTokens + reviewEvent("")), nil,
			`{"outcome":"clean","findings":"","model":"gemini/gemini-3.8-flash","priced":true,` + usage + `,` + reviewed + `}`},
		"findings": {replyWith(usedTokens + reviewEvent("x is missing")), nil,
			`{"outcome":"findings","findings":"x is missing","model":"gemini/gemini-3.8-flash","priced":true,` + usage + `,` + reviewed + `}`},
		"no verdict": {failing, nil,
			`{"outcome":"no-verdict","findings":"","model":"","priced":false,` + noUsage + `,"attempts":[{"model":"gemini/gemini-3.8-flash","outcome":"agent failed","cost":0}]}`},
		"allowance exhausted": {failing, map[string]string{freeReviewModel: allowanceStderr},
			`{"outcome":"no-verdict","findings":"","model":"","priced":false,` + noUsage + `,"attempts":[{"model":"gemini/gemini-3.8-flash","outcome":"allowance exhausted","cost":0}]}`},
	} {
		t.Run(name, func(t *testing.T) {
			var prompts []string
			agent := modelAgent{replies: map[string]func(context.Context, io.Writer) error{freeReviewModel: tt.reply}, prompts: &prompts, stderr: tt.stderr}
			c := validPRContext()
			v, err := ReviewPRWithSpecialists(context.Background(), agent, []string{freeReviewModel}, time.Minute, c, nil, passOf(ReviewAreas()...))
			if err != nil {
				t.Fatal(err)
			}
			if len(prompts) != 1 || prompts[0] != PRReviewPrompt(c.Diff, c.Ticket) {
				t.Fatalf("prompts = %q, want the general prompt alone", prompts)
			}
			if got := string(encodeJSON(t, v)); got != tt.golden {
				t.Fatalf("verdict JSON = %s\nwant       %s", got, tt.golden)
			}
		})
	}
}

