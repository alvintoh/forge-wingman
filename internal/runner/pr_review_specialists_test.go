// TestParsePRVerdictRefusesASpecialistWithAKeyMissing: an absent key reads as the
// zero value, so the reader asks for each key the writer always emits.
func TestParsePRVerdictRefusesASpecialistWithAKeyMissing(t *testing.T) {
	const general = `"outcome":"clean","findings":"","model":"gemini/gemini-3.8-flash","priced":false,` +
		`"usage":{"input":0,"output":0,"reasoning":0,"cache_read":0,"cache_write":0,"cost":0,"steps":0},` +
		`"attempts":[{"model":"gemini/gemini-3.8-flash","outcome":"reviewed","cost":0}]`
	full := map[string]string{
		"name": `"data"`, "outcome": `"reviewed"`, "reason": `""`, "findings": `""`, "model": `"opencode-go/spec-a"`, "priced": `false`,
		"usage": `{"input":0,"output":0,"reasoning":0,"cache_read":0,"cache_write":0,"cost":0,"steps":0}`, "cost": `0`,
		"attempts": `[{"model":"opencode-go/spec-a","outcome":"reviewed","cost":0}]`,
	}
	entry := func(skip string) []byte {
		var parts []string
		for _, k := range specialistKeys {
			if k != skip {
				parts = append(parts, `"`+k+`":`+full[k])
			}
		}
		return []byte(`{` + general + `,"specialists":[{` + strings.Join(parts, ",") + `}]}`)
	}
	if _, err := ParsePRVerdict(entry("")); err != nil {
		t.Fatalf("the complete entry is refused: %v", err)
	}
	for _, k := range specialistKeys {
		if _, err := ParsePRVerdict(entry(k)); !errors.Is(err, ErrPRReviewInvalid) {
			t.Errorf("without %q: err = %v, want ErrPRReviewInvalid", k, err)
		}
	}
	unknown := strings.Replace(string(entry("")), `"name":"data"`, `"name":"data","extra":1`, 1)
	if _, err := ParsePRVerdict([]byte(unknown)); !errors.Is(err, ErrPRReviewInvalid) {
		t.Errorf("an unknown key: err = %v, want ErrPRReviewInvalid", err)
	}
}

// TestParsePRVerdictAcceptsTheWorstVerdictTheRunnerWrites: the general findings
// and those of every configured area, each at its cap and made of the characters
// JSON escapes longest, with a full set of attempts each, still fit the cap the
// reader enforces. It fails when the configured areas outgrow that cap.
func TestParsePRVerdictAcceptsTheWorstVerdictTheRunnerWrites(t *testing.T) {
	// < & and NUL each encode to six bytes; the remainder is quotes, two bytes each.
	escaped := func(n int) string { return strings.Repeat("<&\x00", n/3) + strings.Repeat(`"`, n%3) }
	general := slices.Repeat([]PRReviewAttempt{{Model: "opencode-go/claude-haiku-5-5", Outcome: AttemptTimedOut, Cost: 1}}, maxPRReviewAttempts)
	v := PRVerdict{Outcome: PRReviewFindings, Findings: escaped(maxPRFindingsBytes), Model: freeReviewModel, Attempts: general}
	for _, a := range ReviewAreas() {
		attempts := append(slices.Repeat([]PRReviewAttempt{{Model: specModelB, Outcome: AttemptTimedOut, Cost: 1}}, maxPRReviewAttempts-1),
			PRReviewAttempt{Model: specModelA, Outcome: AttemptReviewed, Cost: 1})
		v.Specialists = append(v.Specialists, SpecialistVerdict{Name: a.Name, Outcome: SpecialistReviewed, Model: specModelA,
			Findings: escaped(maxPRSpecialistFindingsBytes), Cost: attemptsCost(attempts), Attempts: attempts})
	}
	raw := encodeJSON(t, v)
	if len(raw) <= 128<<10 {
		t.Fatalf("the worst verdict is %d bytes, which no longer exceeds the old cap this test guards", len(raw))
	}
	if _, err := ParsePRVerdict(raw); err != nil {
		t.Fatalf("err = %v, want the worst verdict (%d bytes) read back", err, len(raw))
	}
}

