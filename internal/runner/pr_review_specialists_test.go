// TestReviewPRWithSpecialistsKeepsAFailedSpecialistAndRunsTheRest: a specialist
// no model answers is not reviewed, with each attempt, and neither the general
// review nor the specialists after it are affected.
func TestReviewPRWithSpecialistsKeepsAFailedSpecialistAndRunsTheRest(t *testing.T) {
	failing := func(context.Context, io.Writer) error { return errors.New("exit status 1") }
	hanging := func(ctx context.Context, _ io.Writer) error { <-ctx.Done(); return ctx.Err() }
	for name, tt := range map[string]struct {
		reply      func(context.Context, io.Writer) error
		stderr     string
		wantReason string
		wantCost   float64
		wantOutcom string
	}{
		"every model failing":     {failing, "", SpecialistReasonFailed, 0, AttemptFailed},
		"every model timing out":  {hanging, "", SpecialistReasonTimedOut, 0, AttemptTimedOut},
		"every model unreadable":  {replyWith(tokensCosting("0.25") + planEvent("no block")), "", SpecialistReasonUnreadable, 0.5, AttemptUnreadable},
		"every allowance spent":   {failing, allowanceStderr, SpecialistReasonExhausted, 0, AttemptExhausted},
		"a timeout and a failure": {nil, "", SpecialistReasonFailed, 0, ""},
	} {
		t.Run(name, func(t *testing.T) {
			var prompts []string
			replies := map[string]func(context.Context, io.Writer) error{
				freeReviewModel: replyWith(reviewEvent("g")), specModelA: tt.reply, specModelB: tt.reply,
				"opencode-go/spec-c": replyWith(reviewEvent("i")),
			}
			stderr := map[string]string{specModelA: tt.stderr, specModelB: tt.stderr}
			if tt.reply == nil {
				replies[specModelA], replies[specModelB] = hanging, failing
			}
			agent := modelAgent{replies: replies, prompts: &prompts, stderr: stderr}
			v, err := ReviewPRWithSpecialists(context.Background(), agent, []string{freeReviewModel}, 50*time.Millisecond, contextTouching(), nil,
				passOf(areaOf(t, "data", specModelA, specModelB), areaOf(t, "infra", "opencode-go/spec-c")))
			if err != nil {
				t.Fatal(err)
			}
			if v.Outcome != PRReviewFindings || v.Findings != "g" || !slices.Equal(specialistNames(v), []string{"data", "infra"}) {
				t.Fatalf("verdict = %+v", v)
			}
			data, infra := v.Specialists[0], v.Specialists[1]
			if data.Outcome != SpecialistNotReviewed || data.Reason != tt.wantReason || data.Findings != "" || data.Model != "" ||
				len(data.Attempts) != 2 || data.Cost != tt.wantCost {
				t.Fatalf("data = %+v", data)
			}
			if tt.wantOutcom != "" && !slices.Equal(outcomesOf(data.Attempts), []string{tt.wantOutcom, tt.wantOutcom}) {
				t.Fatalf("data attempts = %+v", data.Attempts)
			}
			if infra.Outcome != SpecialistReviewed || infra.Findings != "i" {
				t.Fatalf("infra = %+v", infra)
			}
			if _, err := ParsePRVerdict(encodeJSON(t, v)); err != nil {
				t.Fatalf("the verdict does not parse back: %v", err)
			}
		})
	}
}

func TestReviewPRWithSpecialistsSkipsASpecialistTheDeadlineReaches(t *testing.T) {
	deadline := time.Now().Add(time.Hour)
	for name, tt := range map[string]struct {
		// passedAfter is how many agent calls the clock reaches the deadline after,
		// -1 for never, and offset is how far past it reads.
		passedAfter int
		offset      time.Duration
		wantRan     []string
		wantSkipped []string
	}{
		"before the second starts": {2, time.Minute, []string{"data"}, []string{"infra"}},
		"exactly at the deadline":  {2, 0, []string{"data"}, []string{"infra"}},
		"before the first starts":  {1, time.Second, nil, []string{"data", "infra"}},
		"never reached":            {-1, 0, []string{"data", "infra"}, nil},
	} {
		t.Run(name, func(t *testing.T) {
			var prompts []string
			agent := modelAgent{replies: map[string]func(context.Context, io.Writer) error{
				freeReviewModel: replyWith(reviewEvent("")), specModelA: replyWith(reviewEvent("d")),
			}, prompts: &prompts}
			// The injected clock stands in for the wall clock the starts are checked
			// against; the hard stop on a running attempt is real time, an hour away.
			now := func() time.Time {
				if tt.passedAfter >= 0 && len(prompts) >= tt.passedAfter {
					return deadline.Add(tt.offset)
				}
				return deadline.Add(-time.Minute)
			}
			pass := SpecialistPass{Areas: []ReviewArea{areaOf(t, "data", specModelA), areaOf(t, "infra", specModelA)}, Deadline: deadline, Now: now}
			v, err := ReviewPRWithSpecialists(context.Background(), agent, []string{freeReviewModel}, time.Minute, contextTouching(), nil, pass)
			if err != nil {
				t.Fatal(err)
			}
			var ran, skipped []string
			for _, s := range v.Specialists {
				switch {
				case s.Outcome == SpecialistReviewed:
					ran = append(ran, s.Name)
				case s.Reason == SpecialistReasonDeadline && s.Outcome == SpecialistNotReviewed && len(s.Attempts) == 0 && s.Model == "":
					skipped = append(skipped, s.Name)
				}
			}
			if !slices.Equal(ran, tt.wantRan) || !slices.Equal(skipped, tt.wantSkipped) || len(prompts) != 1+len(tt.wantRan) {
				t.Fatalf("ran %v, skipped %v, %d agent calls; verdict = %+v", ran, skipped, len(prompts), v)
			}
			if _, err := ParsePRVerdict(encodeJSON(t, v)); err != nil {
				t.Fatalf("the verdict does not parse back: %v", err)
			}
		})
	}
}

